-- FoundIt tables. See docs/backend-foundation-design.md

create table users (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null unique,
  password_hash text not null,
  alerts_on boolean not null default true,
  created_at timestamptz not null default now()
);

create table categories (
  name text primary key,
  related text[] not null default '{}'
);

create table campus_spots (
  id bigint generated by default as identity primary key,
  building text not null,
  floor text not null,
  area text not null,
  lat double precision not null,
  lng double precision not null,
  linked_buildings text[] not null default '{}',
  is_collection_point boolean not null default false,
  unique (building, floor, area)
);

create table items (
  id bigint generated by default as identity primary key,
  type text not null check (type in ('lost', 'found')),
  title text not null,
  description text not null default '',
  category text not null references categories (name),
  colour text,
  brand text,
  photo_url text,
  status text not null default 'open'
    check (status in ('open', 'matched', 'resolved', 'archived')),
  posted_by bigint not null references users (id) on delete cascade,
  created_at timestamptz not null default now()
);

create table item_trail_points (
  id bigint generated by default as identity primary key,
  item_id bigint not null references items (id) on delete cascade,
  spot_id bigint not null references campus_spots (id),
  from_time timestamptz not null,
  to_time timestamptz not null,
  position integer not null default 0,
  check (from_time <= to_time)
);

create table matches (
  id bigint generated by default as identity primary key,
  lost_item_id bigint not null references items (id) on delete cascade,
  found_item_id bigint not null references items (id) on delete cascade,
  score numeric not null check (score between 0 and 100),
  breakdown jsonb not null default '{}',
  reasons text[] not null default '{}',
  status text not null default 'suggested'
    check (status in ('suggested', 'claimed', 'confirmed', 'rejected')),
  created_at timestamptz not null default now(),
  unique (lost_item_id, found_item_id)
);

create table claims (
  id bigint generated by default as identity primary key,
  match_id bigint not null references matches (id) on delete cascade,
  question text not null,
  answer_hash text not null,
  attempts integer not null default 0,
  verified boolean not null default false,
  created_at timestamptz not null default now()
);

create table messages (
  id bigint generated by default as identity primary key,
  match_id bigint not null references matches (id) on delete cascade,
  sender_id bigint not null references users (id) on delete cascade,
  text text not null,
  sent_at timestamptz not null default now()
);

create table handoffs (
  id bigint generated by default as identity primary key,
  match_id bigint not null references matches (id) on delete cascade,
  method text not null check (method in ('meetup', 'drop-off')),
  spot_id bigint references campus_spots (id),
  scheduled_at timestamptz,
  status text not null default 'pending' check (status in ('pending', 'completed')),
  created_at timestamptz not null default now()
);

create index items_type_status_category_idx on items (type, status, category);
create index item_trail_points_item_idx on item_trail_points (item_id);
create index item_trail_points_spot_idx on item_trail_points (spot_id);
create index matches_lost_item_idx on matches (lost_item_id);
create index matches_found_item_idx on matches (found_item_id);
create index claims_match_idx on claims (match_id);
create index handoffs_match_idx on handoffs (match_id);
create index messages_match_sent_idx on messages (match_id, sent_at);

-- Only the server (service_role) may touch the data. Row Level Security with
-- no policies blocks the public browser keys completely.
alter table users enable row level security;
alter table categories enable row level security;
alter table campus_spots enable row level security;
alter table items enable row level security;
alter table item_trail_points enable row level security;
alter table matches enable row level security;
alter table claims enable row level security;
alter table messages enable row level security;
alter table handoffs enable row level security;

revoke all on all tables in schema public from anon, authenticated;
grant all on all tables in schema public to service_role;
grant usage, select on all sequences in schema public to service_role;

-- Empties every table and restarts the id counters. Used by the seed script.
create function reset_all_tables() returns void
language sql security definer set search_path = public as $$
  truncate table handoffs, messages, claims, matches, item_trail_points,
    items, campus_spots, categories, users restart identity cascade;
$$;

-- After seeding with explicit ids, moves each counter past the highest id.
create function sync_id_sequences() returns void
language plpgsql security definer set search_path = public as $$
begin
  perform setval(pg_get_serial_sequence('users', 'id'),
    coalesce((select max(id) from users), 0) + 1, false);
  perform setval(pg_get_serial_sequence('campus_spots', 'id'),
    coalesce((select max(id) from campus_spots), 0) + 1, false);
  perform setval(pg_get_serial_sequence('items', 'id'),
    coalesce((select max(id) from items), 0) + 1, false);
end;
$$;

revoke execute on function reset_all_tables() from public, anon, authenticated;
revoke execute on function sync_id_sequences() from public, anon, authenticated;
grant execute on function reset_all_tables() to service_role;
grant execute on function sync_id_sequences() to service_role;
