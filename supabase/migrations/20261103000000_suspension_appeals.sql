-- Suspension appeals (feature 5, decided 2026-11-03). A suspended student can
-- ask an admin to lift the suspension, once for each suspension. An admin
-- lifts it or keeps it, with a reply the student reads on their appeal page.
--
-- reset_all_tables() needs no change: it truncates users with cascade, which
-- empties this table too.

create table appeals (
  id bigint generated by default as identity primary key,
  user_id bigint not null references users (id) on delete cascade,
  -- Which suspension this is about: the account's suspended_at when it was sent
  suspended_at timestamptz not null,
  message text not null,
  proof_url text,
  status text not null default 'open' check (status in ('open', 'accepted', 'declined')),
  reply text,
  decided_by bigint references users (id) on delete set null,
  decided_at timestamptz,
  created_at timestamptz not null default now(),
  -- One appeal for each suspension
  unique (user_id, suspended_at)
);

create index appeals_status_idx on appeals (status, created_at);

-- Same rule as every other table: only the server's key may read or write
alter table appeals enable row level security;

-- Keeping a suspension after an appeal goes in the action log too, and a log
-- entry can point at the appeal it answered
alter table admin_actions drop constraint admin_actions_action_check;
alter table admin_actions add constraint admin_actions_action_check check (action in (
  'uphold_dispute', 'close_dispute', 'dismiss_report', 'warn_user',
  'remove_message', 'remove_item', 'suspend_user', 'unsuspend_user', 'decline_appeal'
));
alter table admin_actions add column appeal_id bigint references appeals (id) on delete set null;
