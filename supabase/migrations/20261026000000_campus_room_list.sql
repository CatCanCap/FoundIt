-- Every bookable room in SMU's facility booking system (FBS, read on
-- 26 October 2026), so a report can name the exact room: "LKCSB Seminar Room
-- 3-2", not just "LKCSB Level 3, seminar rooms". 392 rooms in 9 buildings.
--
-- How places fit together after this:
--   campus_spots  a building, level and area, as before ("LKCSB", "Level 3",
--                 "seminar rooms"). Every item and meetup still points at one.
--   campus_rooms  new. One row per bookable room, each in one area:
--                 ("LKCSB Seminar Room 3-2" is in LKCSB / Level 3 / seminar rooms).
--   item_trail_points.room_id  new and optional. A report names a room only
--                 when the person knows it; the area is always there.
-- A trail point's room must be in that point's own area. The database checks
-- this itself (the foreign key on room_id and spot_id together), so no code
-- can save a room from another building by mistake.
--
-- The booking system is now the source of truth for room types:
--   1. 5 areas it has rooms in are added (seminar rooms on LKCSB Level 1,
--      SOA Level 1, SCIS 1 Basement 1 and SOE/SCIS 2 Basement 1, and the SMU
--      Connexion Jamming Room on Level 4).
--   2. 86 room-type areas it has no rooms in go (for example meeting pods on
--      most levels). Anything that points at one first moves to the same
--      level's study area, or else its lifts, stairs & corridors, so no item or
--      meetup is lost.
-- Lobbies, food, study areas, toilets, lifts and named places stay as they are.
-- The same list is in server/data/campus-spots.json for the seed.

-- 1. The rooms
create table campus_rooms (
  id bigint generated by default as identity primary key,
  spot_id bigint not null references campus_spots (id) on delete cascade,
  -- As the booking system names it, e.g. 'LKCSB Seminar Room 3-2'
  name text not null unique,
  -- The order the API lists rooms in (file order, by room number)
  position integer not null default 100000,
  -- Lets item_trail_points check a room against its area (step 2)
  unique (id, spot_id)
);

create index campus_rooms_spot_idx on campus_rooms (spot_id);

-- 2. A trail point can name a room in its area. With no room, room_id is null
-- and the check is skipped.
alter table item_trail_points add column room_id bigint;
alter table item_trail_points
  add constraint item_trail_points_room_in_area
  foreign key (room_id, spot_id) references campus_rooms (id, spot_id);

create index item_trail_points_room_idx on item_trail_points (room_id);

-- Like every other table, only the server's secret key can read or write it
alter table campus_rooms enable row level security;
revoke all on campus_rooms from anon, authenticated;
grant all on campus_rooms to service_role;

-- The seed script and the API tests empty campus_rooms with the other tables,
-- and move its id counter past the ids the seed gives
create or replace function reset_all_tables() returns void
language sql security definer set search_path = public as $$
  truncate table admin_actions, reports, disputes, handoffs, messages, claims,
    matches, item_colours, item_trail_points, items, campus_rooms, campus_spots,
    categories, users
    restart identity cascade;
$$;

create or replace function sync_id_sequences() returns void
language plpgsql security definer set search_path = public as $$
begin
  perform setval(pg_get_serial_sequence('users', 'id'),
    coalesce((select max(id) from users), 0) + 1, false);
  perform setval(pg_get_serial_sequence('campus_spots', 'id'),
    coalesce((select max(id) from campus_spots), 0) + 1, false);
  perform setval(pg_get_serial_sequence('campus_rooms', 'id'),
    coalesce((select max(id) from campus_rooms), 0) + 1, false);
  perform setval(pg_get_serial_sequence('items', 'id'),
    coalesce((select max(id) from items), 0) + 1, false);
end;
$$;

