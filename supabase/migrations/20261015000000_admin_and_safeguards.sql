-- The final (v2) proposal: feature 5 is now admin and safeguards.
--   * Claims are no longer gated by a hidden question. The owner claims a match
--     with one detail only the owner would know, the chat opens, and the
--     finder may decline the claim.
--   * Users have a role (user or admin), verify their SMU email with a code,
--     and can be suspended.
--   * Anyone who thinks a claimed item is theirs can open a dispute, which an
--     admin decides. Chat messages and posts can be reported to an admin.
--   * Every admin action is logged.
--
-- This file only ADDS things, so code on `dev` keeps working against a
-- database that has run it. The hidden-question columns and the watched-places
-- table stay until supabase/pending/drop_hidden_question_and_watched_places.sql
-- is moved into this folder, together with the new claim routes (WS5).

-- 1. Roles and suspension. A suspended user may still log in and read, but
--    cannot post, claim or chat (checked by requireAuth on the server).
alter table users
  add column role text not null default 'user' check (role in ('user', 'admin')),
  add column suspended_at timestamptz;

-- 2. Proof that the person owns the SMU inbox. A new account gets a 6-digit
--    code by email and cannot post, claim or chat until it enters it. Only a
--    hash of the code is kept. Accounts made before this change count as
--    verified, so nobody already using the app is locked out.
alter table users
  add column email_verified_at timestamptz,
  add column verify_code_hash text,
  add column verify_code_expires_at timestamptz,
  add column verify_code_sent_at timestamptz,
  add column verify_attempts integer not null default 0;

update users set email_verified_at = created_at;

-- 3. A claim is now "this is mine" from the owner of the lost item, logged
--    against their account, with one detail only the owner would know (shown
--    to the finder, and to an admin in a dispute).
--    status: active, declined (by the finder), withdrawn (by the claimer after
--    a dispute), overturned (an admin returned the item to someone else)
--    The old question columns become optional now and are dropped later.
alter table claims
  add column claimer_id bigint references users (id) on delete cascade,
  add column detail text,
  add column status text not null default 'active'
    check (status in ('active', 'declined', 'withdrawn', 'overturned')),
  add column decided_at timestamptz,
  alter column question drop not null,
  alter column answer_hash drop not null;

update claims
set claimer_id = items.posted_by
from matches
join items on items.id = matches.lost_item_id
where matches.id = claims.match_id;

-- At most one active claim per match
create unique index claims_one_active_per_match on claims (match_id) where status = 'active';
create index claims_claimer_idx on claims (claimer_id);

-- 4. An admin can take a post down. Removed items leave the feed and matching,
--    but the row stays so the action log still points at it.
alter table items drop constraint items_status_check;
alter table items
  add constraint items_status_check
    check (status in ('open', 'matched', 'resolved', 'archived', 'removed'));

-- A post with 3 open reports hides itself until an admin looks at it
alter table items add column hidden_at timestamptz;

-- An admin can take a chat message down. Its text is hidden from the chat.
alter table messages add column removed_at timestamptz;

-- 5. Disputes: "This is my item" on a claimed found item
--    status: open -> upheld (an admin returned it to the person who raised it)
--                 -> closed (an admin kept the claim)
--                 -> withdrawn (the claimer gave it up; it goes to the person who raised it)
create table disputes (
  id bigint generated by default as identity primary key,
  -- The found item and the claim being disputed
  item_id bigint not null references items (id) on delete cascade,
  claim_id bigint not null references claims (id) on delete cascade,
  raised_by bigint not null references users (id) on delete cascade,
  -- The person's own lost report, attached automatically (required to dispute)
  lost_item_id bigint references items (id) on delete set null,
  description text not null,
  proof_url text,
  -- The claimer's side
  claimer_response text,
  claimer_proof_url text,
  responded_at timestamptz,
  status text not null default 'open' check (status in ('open', 'upheld', 'closed', 'withdrawn')),
  decision_reason text,
  -- When upheld after the claimer already had the item: the date by which
  -- they must bring it to a collection point
  return_by timestamptz,
  -- The claim the item moved to, when it went back to the person who raised it
  new_claim_id bigint references claims (id) on delete set null,
  decided_by bigint references users (id) on delete set null,
  decided_at timestamptz,
  created_at timestamptz not null default now()
);

create unique index disputes_one_open_per_person on disputes (claim_id, raised_by) where status = 'open';
create index disputes_item_idx on disputes (item_id);
create index disputes_status_idx on disputes (status, created_at);

-- 6. Reports of a chat message or a fake post
create table reports (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('message', 'item')),
  message_id bigint references messages (id) on delete cascade,
  item_id bigint references items (id) on delete cascade,
  reported_by bigint not null references users (id) on delete cascade,
  reason text not null,
  status text not null default 'open' check (status in ('open', 'dismissed', 'actioned')),
  decided_by bigint references users (id) on delete set null,
  decided_at timestamptz,
  created_at timestamptz not null default now(),
  check ((kind = 'message') = (message_id is not null)),
  check ((kind = 'item') = (item_id is not null))
);

create unique index reports_one_open_per_person
  on reports (kind, coalesce(message_id, item_id), reported_by) where status = 'open';
create index reports_status_idx on reports (status, created_at);

-- 7. The admin action log. Rows are never edited or deleted by the app, and
--    keep their meaning even if what they point at is deleted later.
create table admin_actions (
  id bigint generated by default as identity primary key,
  admin_id bigint references users (id) on delete set null,
  action text not null check (action in (
    'uphold_dispute', 'close_dispute', 'dismiss_report', 'warn_user',
    'remove_message', 'remove_item', 'suspend_user', 'unsuspend_user'
  )),
  dispute_id bigint references disputes (id) on delete set null,
  report_id bigint references reports (id) on delete set null,
  -- The user, item or message the action was taken on
  user_id bigint references users (id) on delete set null,
  item_id bigint references items (id) on delete set null,
  message_id bigint references messages (id) on delete set null,
  reason text not null default '',
  created_at timestamptz not null default now()
);

create index admin_actions_created_idx on admin_actions (created_at desc);

-- Same rule as every other table: only the server's key may read or write
alter table disputes enable row level security;
alter table reports enable row level security;
alter table admin_actions enable row level security;
revoke all on disputes, reports, admin_actions from anon, authenticated;
grant all on disputes, reports, admin_actions to service_role;

-- The seed script and the API tests empty every table, the new ones included
create or replace function reset_all_tables() returns void
language sql security definer set search_path = public as $$
  truncate table admin_actions, reports, disputes, handoffs, messages, claims,
    matches, item_trail_points, items, campus_spots, categories, users
    restart identity cascade;
$$;

revoke execute on function reset_all_tables() from public, anon, authenticated;
grant execute on function reset_all_tables() to service_role;
